export function translateLogLine(line, locale = "en") {
  if (locale !== "ru" || typeof line !== "string") return line;

  const levelMap = {
    INFO: "ИНФО",
    SUCCESS: "УСПЕХ",
    ERROR: "ОШИБКА",
    WARNING: "ПРЕДУПРЕЖДЕНИЕ",
  };
  const marketLogMatch = line.match(/^(\[[^\]]+\]\s+\[)([A-Z]+)(\]\s+)(.*)$/);
  if (marketLogMatch) {
    const [, prefix, level, middle, message] = marketLogMatch;
    return `${prefix}${levelMap[level] || level}${middle}${translateRuntimeText(message, locale)}`;
  }

  const mergeLogMatch = line.match(/^(\[[^\]]+\]\s+)(.*)$/);
  if (mergeLogMatch) {
    const [, prefix, message] = mergeLogMatch;
    return `${prefix}${translateRuntimeText(message, locale)}`;
  }

  return translateRuntimeText(line, locale);
}

export function createI18n(locale = "en") {
  const currentLocale = locale === "ru" ? "ru" : "en";
  const fallback = UI_TEXT.en;
  const dict = UI_TEXT[currentLocale];

  return {
    locale: currentLocale,
    t(key, params = {}) {
      return interpolate(dict[key] ?? fallback[key] ?? key, params);
    },
    rt(text) {
      return translateRuntimeText(text, currentLocale);
    },
    log(text) {
      return translateLogLine(text, currentLocale);
    },
    browserLocale: toBrowserLocale(currentLocale),
    translateReplacementValue,
  };
}
